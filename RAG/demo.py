# Helper functions for video processing and data loading.

def load_metadata(json_filepath: str) -> dict:
    """Extracts specific metadata from a video's JSON metadata file."""
    with open(json_filepath, 'r', encoding='utf-8') as f:
        data = json.load(f)
    video_id = data.get('original_json_filename', 'N/A').replace('.json', '')
    description = data.get('content_metadata', {}).get('description', 'N/A')
    return {
        'id': video_id,
        'description': description
    }

def load_embedding(video_output_dir: str) -> dict:
    """Loads embedding vectors from a specified directory."""
    metadata_path = os.path.join(video_output_dir, "metadata.json")
    with open(metadata_path, "r", encoding="utf-8") as f:
        metadata = json.load(f)
    video_emb = np.load(os.path.join(video_output_dir, metadata["embeddings"]["video_embeddings_path"]))
    text_emb = np.load(os.path.join(video_output_dir, metadata["embeddings"]["text_embeddings_path"]))
    return {
        "video_embeddings": np.squeeze(video_emb).tolist(),
        "text_embeddings": np.squeeze(text_emb).tolist()
    }

def pil_to_base64(image: Image) -> str:
    """Converts a PIL Image object to a base64-encoded string."""
    buffered = BytesIO()
    image.save(buffered, format="PNG")
    return base64.b64encode(buffered.getvalue()).decode("utf-8")

def extract_frames_by_count(video_path: str, num_frames: int = 8) -> List[Image.Image]:
    """Extracts a specified number of frames from a video."""
    frames = []
    container = av.open(video_path)
    stream = container.streams.video[0]
    total_frames = stream.frames
    interval = max(1, total_frames // num_frames)
    for i, frame in enumerate(container.decode(stream)):
        if len(frames) == num_frames:
            break
        if i % interval == 0:
            frames.append(frame.to_image())
    container.close()
    return frames

def get_base64_images_from_name(video_filename: str, video_dir: str = 'videos') -> List[str]:
    """
    Extracts frames from a video file and returns them as a list of base64 strings.
    """
    video_path = os.path.join(video_dir, video_filename)
    extracted_images = extract_frames_by_count(video_path)
    return [pil_to_base64(img) for img in extracted_images]

